retiro = int(input("Valor a retirar: "))

while retiro >= 100:
    print(100)
    retiro -= 100

while retiro >= 50:
    print(50)
    retiro -= 50

while retiro >= 20:
    print(20)
    retiro -= 20

while retiro >= 10:
    print(10)
    retiro -= 10

while retiro >= 5:
    print(5)
    retiro -= 5

while retiro >= 1:
    print(1)
    retiro -= 1